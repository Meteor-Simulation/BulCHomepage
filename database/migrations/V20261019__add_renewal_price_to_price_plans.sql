-- 갱신 금액을 첫 결제와 다르게 둘 수 있게 한다.
--
-- ## 왜 필요한가 — 하드웨어를 묶어 파는 요금제
--
-- 하드웨어가 포함된 Premium 요금제는 첫 해에만 하드웨어 대금(390만원)이 붙는다.
--
--   첫 결제   9,900,000  (소프트웨어 6,000,000 + 하드웨어 3,900,000)
--   2년차~    6,000,000  (소프트웨어만)
--
-- 지금은 price_plans.price 하나뿐이라 둘 중 하나만 맞출 수 있다.
-- SubscriptionBillingService 가 갱신 때도 price 를 그대로 쓰기 때문이다.
--
--   price=9,900,000 으로 두면 → 2년차에도 990만원이 청구된다 (390만원 과다)
--   price=6,000,000 으로 두면 → 첫 해에 390만원을 덜 받는다
--
-- 어느 쪽이든 틀린다. 그래서 갱신가를 따로 둔다.
--
-- ## 왜 첫 결제 쪽이 아니라 갱신 쪽에 컬럼을 두는가
--
-- 반대로 "price 는 600만원으로 두고 첫 결제에 390만원을 더한다" 도 가능하다. 그러나 그쪽은
-- 금액 검증·쿠폰 계산·멱등키가 모두 모여 있는 **첫 결제 경로**를 건드려야 한다. 이 프로젝트에서
-- 이중 청구가 두 번 난 자리가 정확히 거기다(2026-10-07 · 10-12). 갱신 스케줄러만 손대는 쪽이
-- 사고 반경이 훨씬 작다.
--
-- ## NULL 의 의미
--
-- NULL = "갱신도 price 와 같다". 기존 요금제는 전부 NULL 로 남고 동작이 바뀌지 않는다.
-- 하드웨어 포함 요금제에만 값을 넣는다.
--
-- CHAR 가 아니라 DECIMAL 을 쓰고, price 와 같은 정밀도(18,2)로 맞춘다.

ALTER TABLE price_plans
    ADD COLUMN IF NOT EXISTS renewal_price DECIMAL(18,2) NULL;

COMMENT ON COLUMN price_plans.renewal_price IS '자동갱신 시 청구할 금액. NULL 이면 price 와 같다. 첫 해에만 하드웨어 대금이 붙는 요금제처럼 첫 결제와 갱신가가 다를 때만 채운다';
